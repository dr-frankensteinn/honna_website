-- Run once in the Supabase SQL editor (safe to re-run).
-- Locks every table and the photo bucket so only the people listed in `members` can read or write.
-- This file holds no personal data; that goes in private/seed.sql, which is never committed.

-- Who may get in -------------------------------------------------------------
create table if not exists public.members (
  email        text primary key,
  role         text not null check (role in ('admin', 'partner')),
  display_name text
);

create or replace function public.is_member() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.members where lower(email) = lower(auth.jwt() ->> 'email'))
$$;

-- Content tables (created if missing, extended if they already exist) -------
create table if not exists public.settings (
  key   text primary key,
  value text
);

create table if not exists public.timeline (
  id          bigint generated by default as identity primary key,
  date        text,
  title       text,
  "desc"      text,
  journal_img text
);
alter table public.timeline add column if not exists sort_date  date;
alter table public.timeline add column if not exists image_path text;
alter table public.timeline add column if not exists note_path  text;

create table if not exists public.photos (
  id      bigint generated by default as identity primary key,
  url     text,
  caption text
);
alter table public.photos add column if not exists path        text;
alter table public.photos add column if not exists uploaded_by text;
alter table public.photos add column if not exists created_at  timestamptz default now();
alter table public.photos alter column url drop not null;

create table if not exists public.bucketlist (
  id       bigint generated by default as identity primary key,
  text     text,
  category text,
  done     boolean default false
);

create table if not exists public.status (
  id     int primary key,
  status text,
  mood   text
);
alter table public.status add column if not exists updated_at timestamptz default now();

-- Row level security: drop every old policy, then members-only ---------------
do $$
declare p record;
begin
  for p in select policyname, tablename from pg_policies
           where schemaname = 'public'
             and tablename in ('members', 'settings', 'timeline', 'photos', 'bucketlist', 'status')
  loop
    execute format('drop policy %I on public.%I', p.policyname, p.tablename);
  end loop;
end $$;

alter table public.members    enable row level security;
alter table public.settings   enable row level security;
alter table public.timeline   enable row level security;
alter table public.photos     enable row level security;
alter table public.bucketlist enable row level security;
alter table public.status     enable row level security;

revoke all on public.members, public.settings, public.timeline, public.photos, public.bucketlist, public.status from anon;
grant select on public.members to authenticated;
grant select, insert, update, delete on public.settings, public.timeline, public.photos, public.bucketlist, public.status to authenticated;
grant usage, select on all sequences in schema public to authenticated;

create policy members_read on public.members for select to authenticated using (public.is_member());
create policy members_only on public.settings   for all to authenticated using (public.is_member()) with check (public.is_member());
create policy members_only on public.timeline   for all to authenticated using (public.is_member()) with check (public.is_member());
create policy members_only on public.photos     for all to authenticated using (public.is_member()) with check (public.is_member());
create policy members_only on public.bucketlist for all to authenticated using (public.is_member()) with check (public.is_member());
create policy members_only on public.status     for all to authenticated using (public.is_member()) with check (public.is_member());

-- Private photo bucket -------------------------------------------------------
insert into storage.buckets (id, name, public) values ('photos', 'photos', false)
on conflict (id) do update set public = false;

drop policy if exists "photos: members read"   on storage.objects;
drop policy if exists "photos: members add"    on storage.objects;
drop policy if exists "photos: members change" on storage.objects;
drop policy if exists "photos: members remove" on storage.objects;

create policy "photos: members read"   on storage.objects for select to authenticated using (bucket_id = 'photos' and public.is_member());
create policy "photos: members add"    on storage.objects for insert to authenticated with check (bucket_id = 'photos' and public.is_member());
create policy "photos: members change" on storage.objects for update to authenticated using (bucket_id = 'photos' and public.is_member());
create policy "photos: members remove" on storage.objects for delete to authenticated using (bucket_id = 'photos' and public.is_member());
